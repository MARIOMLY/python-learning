# m1_while.py —— 第 3 周周一 · while 循环：写 1 到 10 累加
# 运行方式： python m1_while.py
# 如果终端卡住不动了，按 Ctrl + C 强制停下（那说明你不小心写了死循环）

# ---------- 第一版：先看得见过程 ----------
print("过程版：")
i = 1
while i <= 10:
    print("现在是第", i, "次循环")
    i += 1          # <-- 删掉这一行会怎样？先猜，再试，然后用 Ctrl+C 停下
print("循环结束")

# ---------- 第二版：累加求和 ----------
print("\n累加版：")
i = 1               # 起点
total = 0           # 累加器
while i <= 10:      # 条件
    total += i      # 循环体
    i += 1          # 变化量：让条件迟早不成立
print("1 到 10 累加 =", total, "（应该是 55）")

